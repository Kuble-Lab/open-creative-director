'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const express = require('express');
const { once } = require('node:events');
const { browserRuntime } = require('./support/browser');
(async () => {
  const runtime = browserRuntime();
  if (runtime.skip) throw new Error(runtime.skip);
  let connected = false, failStatus = false, deleted = 0, starts = 0;
  let role = 'participant';
  const app = express();
  app.get('/api/me', (req, res) => res.json({ active: true, identified: role !== 'anonymous', email: role === 'anonymous' ? null : 'test@example.com', role, isAdmin: false, isSuperAdmin: false, restricted: true, participant: role === 'participant', teams: [], budget: null }));
  app.get('/api/suno/status', (req, res) => failStatus ? res.status(500).json({ error: '<img src=x onerror=alert(1)>' }) : res.json({ connected }));
  app.post('/api/suno/connect', (req, res) => { starts++; res.json({ authorizationUrl: 'https://studio-api-prod.suno.com/api/v2/external/oauth/authorize/?test=1' }); });
  app.delete('/api/suno/auth', (req, res) => { connected = false; deleted++; res.json({ connected: false }); });
  app.get('/', (req, res) => res.type('html').send(`<!doctype html><html><head><meta name="viewport" content="width=device-width, initial-scale=1"><link rel="stylesheet" href="styles.css"></head><body><header id="header" style="padding:24px"></header><script src="i18n.js"></script><script src="suno-ui.js"></script><script src="access-client.js"></script><script src="shell.js"></script><script>document.getElementById('header').append(OCShell.accountMenu({variant:'chat'}).element);</script></body></html>`));
  app.use(express.static(path.resolve(__dirname, '../public')));
  const server = app.listen(0, '127.0.0.1');
  await once(server, 'listening');
  const url = 'http://127.0.0.1:' + server.address().port;
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'suno-ui-'));
  let browser;
  try {
    browser = await runtime.puppeteer.launch({ executablePath: runtime.executablePath, headless: true, userDataDir: temp, args: ['--no-sandbox', '--disable-background-networking'] });
    const page = await browser.newPage();
    page.setDefaultTimeout(10000);
    await page.setViewport({ width: 1100, height: 800 });
    await page.evaluateOnNewDocument(() => localStorage.setItem('vcd-lang', 'de'));
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.setRequestInterception(true);
    page.on('request', request => {
      if (request.url().startsWith(url)) return request.continue();
      if (request.isNavigationRequest() && request.url().startsWith('https://studio-api-prod.suno.com/')) return request.respond({ status: 200, contentType: 'text/html', body: '<p>Mock Suno login</p>' });
      return request.abort();
    });
    const open = async () => {
      await page.click('.account-chip');
      await page.waitForSelector('[data-item="suno"]');
      assert.equal(await page.$('[data-item="settings"]'), null, 'participant needs no admin settings');
      await page.click('[data-item="suno"]');
      await page.waitForSelector('#sunoModal:not(.hidden)');
    };
    await page.goto(url);
    await page.evaluate(() => OCAccess.ready);
    await open();
    await page.waitForSelector('[data-act="connect"]');
    await page.keyboard.press('Escape');
    assert.equal(await page.$eval('#sunoModal', el => el.classList.contains('hidden')), true);
    assert.equal(await page.evaluate(() => document.activeElement.classList.contains('account-chip')), true);
    await open();
    await page.waitForSelector('[data-act="connect"]');
    await Promise.all([page.waitForNavigation(), page.click('[data-act="connect"]')]);
    assert.equal(starts, 1);
    assert.ok(page.url().startsWith('https://studio-api-prod.suno.com/'));
    connected = true;
    await page.goto(url);
    await page.waitForSelector('#sunoModal:not(.hidden) [data-act="disconnect"]');
    assert.match(await page.$eval('#sunoStatus', el => el.textContent), /Verbunden/);
    await page.screenshot({ path: '/tmp/suno-ui-desktop.png' });
    await page.setViewport({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: '/tmp/suno-ui-mobile.png' });
    await page.click('[data-act="disconnect"]');
    assert.equal(deleted, 0);
    await page.click('[data-act="disconnect"]');
    await page.waitForSelector('[data-act="connect"]');
    assert.equal(deleted, 1);
    await page.keyboard.press('Escape');
    failStatus = true;
    await open();
    await page.waitForSelector('[data-act="retry"]');
    assert.match(await page.$eval('#sunoModal', el => el.textContent), /<img src=x/);
    assert.equal(await page.$('#sunoModal img'), null, 'error remains text');
    failStatus = false;
    await page.click('[data-act="retry"]');
    await page.waitForSelector('[data-act="connect"]');
    await page.evaluate(() => { setLang('es'); OCShell.refresh(); });
    assert.match(await page.$eval('[data-act="connect"]', el => el.textContent), /Conectar/);
    await page.keyboard.press('Escape');
    role = 'guest';
    await page.evaluate(() => OCAccess.refreshMe());
    await open();
    await page.waitForSelector('[data-act="connect"]');
    await page.keyboard.press('Escape');
    role = 'anonymous';
    await page.evaluate(() => OCAccess.refreshMe());
    await page.click('.account-chip');
    assert.equal(await page.$('[data-item="suno"]'), null);
    assert.deepEqual(errors, []);
  } finally {
    await browser?.close();
    await new Promise(resolve => server.close(resolve));
    fs.rmSync(temp, { recursive: true, force: true });
  }
  console.log('test-suno-ui.js: ok');
})().catch(error => { console.error(error); process.exitCode = 1; });
